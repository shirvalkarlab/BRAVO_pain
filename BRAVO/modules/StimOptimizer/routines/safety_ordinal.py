"""An ordinal Gaussian-process model of side-effect severity over stimulation parameters.

What problem this file solves
-----------------------------
Until now the safety layer of this module has been :class:`StimOptimizer.routines.surrogate
.SafetyGP`, which is a Gaussian process over a numeric severity score with a prior mean that is
forced to be non-decreasing in stimulation amplitude. That construction embeds two assumptions,
and both of them are now known to be wrong for this participant.

The first assumption is that severity is a number. It is not. The coded acute record labels each
step with one of four ordered categories: none, mild, moderate, severe. Treating those labels as
the numbers 0, 1, 2, 3 and fitting a Gaussian likelihood to them asserts that the step from
"none" to "mild" is the same size as the step from "moderate" to "severe", which nobody has
established and which nothing in the coding procedure was designed to make true. It also lets
the model predict severity values such as 1.4 or -0.3, which correspond to no clinical statement
at all, and it makes the reported uncertainty a statement about a fictitious continuous quantity
rather than about the probability of a category a clinician can act on.

The second assumption is that severity increases with amplitude. In this participant's record it
does not. That is not a modelling preference; it is what the data say, and the numbers are
re-derived from the file every time this module's analysis is run rather than quoted from
memory. A model whose prior mean is constrained to be non-decreasing in amplitude cannot report
that finding, because it has assumed the answer before seeing the data.

What this file does instead
---------------------------
It fits an ordinal Gaussian process. A single latent function ``f`` is given a Gaussian-process
prior over the stimulation parameters, and the observed category is generated by comparing that
latent value against a set of learned cutpoints:

    P(y = k | f) = Phi(c_k - f) - Phi(c_{k-1} - f)

with ``Phi`` the standard normal cumulative distribution function, ``c_0 = 0`` fixed for
identifiability and the remaining cutpoints obtained by adding positive learned increments. This
is the ordered-probit likelihood, and the implementation follows the one in Meta's AEPsych
package, which is the closest published analogue to this problem because it was built for
adaptive psychophysics experiments in which a human being rates a stimulus on an ordered scale.
The two files adapted here are ``aepsych/likelihoods/ordinal.py`` (the cutpoint likelihood, and
the convention that the first cutpoint is fixed at zero) and ``aepsych/models/ordinal_gp.py``
(the variational ordinal GP, the decision to omit an output scale from the kernel because the
latent scale and the cutpoint spacing are not separately identifiable, and the closed-form
moment-matched predictive probabilities). AEPsych is MIT-licensed Meta code; the approach is
adapted rather than copied, and the correspondence is recorded in comments at each place it
matters.

Three properties of this structure matter for the clinical question:

1.  It imposes no monotone dose-response. The latent function is free to rise, fall or stay flat
    in any input, so the model can report that amplitude does not predict severity if that is
    what the data show.
2.  Its output is a probability of a category, not a score. "The posterior probability of a
    moderate-or-worse event at this setting is 4 percent, with a 90 percent credible interval
    from 1 to 12 percent" is a sentence a clinician can act on. "Predicted severity 0.31" is not.
3.  Because the latent function has a Gaussian posterior and the probability of
    moderate-or-worse is a monotone increasing transform of it, credible intervals on that
    probability are available in closed form by transforming the latent quantiles. No sampling
    is needed and the intervals are exact given the variational posterior.

Unknown is not the same as safe
-------------------------------
This is the single most important behaviour in the file. Far from any observation the
variational posterior reverts to the prior: the latent mean returns to the fitted constant and
the latent variance rises to the prior variance, which for a Matern kernel without an output
scale is exactly 1. Because moderate-or-worse events are rare overall, that fitted constant
corresponds to a LOW probability. Reading the estimated probability alone would therefore report
an unobserved region as low-risk, which is precisely the error that must not be made: it would
tell a clinician that a setting nobody has ever delivered is safe, on the strength of the
overall base rate.

Two separate mechanisms prevent that, and it is worth being clear about which does what, because
they fail in different circumstances. The first is the credible interval. Where the latent
variance has reverted to 1 the interval on the probability is very wide, so its upper end
exceeds any reasonable tolerance and the cell cannot be called safe. This is the mechanism that
does most of the work. The second is an explicit requirement for local evidence, which exists
because the first is not guaranteed: if the fitted cutpoints are far apart relative to the
latent scale, a reverted region can have both a low estimated probability and an interval narrow
enough to clear the tolerance. The evidence requirement also matters independently for the
cumulative safe set in :class:`SafeSetTracker`, where an admission can never be withdrawn and
must therefore not rest on the absence of contradicting data.

:meth:`OrdinalSeverityGP.classify` therefore requires two separate conditions before it will
call a cell safe. The upper end of the credible interval on the probability of moderate-or-worse
must fall below a stated threshold, AND the cell must carry a minimum amount of local evidence,
measured as the sum of the fitted kernel's correlation between that cell and every training
observation. That second quantity, ``n_eff``, is an effective local sample size: it equals
roughly the number of observations that are close enough, on the model's own fitted length
scales, to say anything about this cell. A cell that fails either condition without failing the
probability condition in the unsafe direction is labelled ``unknown``, which is a third state
distinct from both ``safe`` and ``elevated``.

Missing labels are missing
--------------------------
Steps whose severity could not be coded are dropped, never recoded as "none". A step read as
no-side-effect would tell the model that an untested region was tolerated, which is the same
category of error as calling an unobserved region safe. :func:`prepare_coded_steps` enforces
this and additionally separates steps whose "none" label came from an explicit coding decision
from steps that were never put through the coding pass at all, because those two are not the
same kind of evidence and the difference turns out to matter here.

Relationship to SAFE-OPT
------------------------
The safe-set bookkeeping in :class:`SafeSetTracker` follows the update rule of Sarikhani et
al.'s SAFE-OPT as implemented in Cole's MATLAB reference (``code/safe_opt_memory/
safe_opt_update_ND.m``), in which the safe set is CUMULATIVE: a grid cell that has ever
qualified stays in the set permanently, so the set grows monotonically and cannot oscillate
between iterations. Only that update rule is borrowed. The model structure is not: in that
reference the safety model and the objective model are literally the same Gaussian process over
a single discriminant score, whereas here pain relief and side-effect severity are different
quantities measured on different scales with different likelihoods. The cumulative rule is
offered but is NOT the default, for the reason given in :class:`SafeSetTracker`.
"""
