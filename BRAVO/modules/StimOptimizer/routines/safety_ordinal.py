#: The ordered severity scale used throughout the acute testing record, lowest first. The order
#: is the whole content of an ordinal model, so it is defined once here and never re-typed.
SEVERITY_LEVELS = ("none", "mild", "moderate", "severe")

#: The category at or above which an event is treated as clinically unacceptable. This matches
#: ``objective.SE_HARD_REJECT``, which makes moderate and severe hard-infeasible for the
#: objective surrogate.
DEFAULT_ADVERSE_LEVEL = "moderate"

#: Default upper bound on the probability of a moderate-or-worse event for a cell to be called
#: safe. This is a stated tolerance, not an estimate: it says that a one-in-twenty chance of a
#: moderate event is the most a clinician is willing to accept at a proposed setting. It is
#: exposed as an argument everywhere so that the choice is visible and can be changed.
DEFAULT_P_ADVERSE_MAX = 0.05

#: Default minimum effective local sample size for a cell to be eligible to be called safe. A
#: value of 3 means the fitted kernel must place the equivalent of three whole observations
#: within its own correlation range of the cell. Below that the cell is reported as unknown
#: however low its estimated probability is.
DEFAULT_MIN_EVIDENCE = 3.0


